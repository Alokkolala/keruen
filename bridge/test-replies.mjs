// Разбор ответов в чате. Сети и WhatsApp не требует.
// «Не подходит» не должно читаться как «нет» по первому слову «не».

const YES = /^\s*(да|беру|согласен|ок|окей|\+|yes|ok)(?![а-яё\w])/i
// «не подходит» — это отказ, но просмотр вперёд нельзя вешать на «не »:
// после пробела там всегда буква. Поэтому варианты разведены.
const NO = /^\s*(?:(?:нет|пас|отказ|no)(?![а-яё\w])|не\s)/i

const CASES = [
  ['да', 'yes'],
  ['Да', 'yes'],
  ['да, беру', 'yes'],
  ['беру', 'yes'],
  ['ок', 'yes'],
  ['+', 'yes'],
  ['нет', 'no'],
  ['Нет спасибо', 'no'],
  ['не подходит', 'no'],
  ['пас', 'no'],
  ['давай', 'other'],
  ['дай подумать', 'other'],
  ['а сколько платят?', 'other'],
  ['нету времени', 'other'],
  ['окей давай', 'yes'],
]

let bad = 0
for (const [text, want] of CASES) {
  const got = YES.test(text) ? 'yes' : NO.test(text) ? 'no' : 'other'
  const ok = got === want
  if (!ok) bad++
  console.log(`${ok ? 'ok    ' : 'ПЛОХО '} «${text}» → ${got}${ok ? '' : ` (ждали ${want})`}`)
}

console.log(bad === 0 ? '\nРазбор ответов держит все случаи.' : `\nПровалов: ${bad}`)
process.exit(bad === 0 ? 0 : 1)
